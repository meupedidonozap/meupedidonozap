import { afterEach, describe, expect, it } from 'vitest';
import { mkdtempSync, mkdirSync, writeFileSync, readFileSync, rmSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { createRequire } from 'node:module';
const { prepareAndroid } = createRequire(import.meta.url)('../../scripts/android/prepare-android.cjs');
const roots: string[] = [];
afterEach(() => roots.splice(0).forEach(root => rmSync(root, { recursive: true, force: true })));
describe('Android least-privilege configuration', () => {
  it('declares read contacts and foreground location only, preserving native customization on repeated runs', () => {
    const root = mkdtempSync(join(tmpdir(), 'mpz-android-'));
    roots.push(root);
    const main = join(root, 'android/app/src/main');
    const java = join(main, 'java/app/lovable/dfc9e1d2017c4c4499328af8ac12f08f');
    mkdirSync(java, { recursive: true });
    mkdirSync(join(root, 'scripts/android'), { recursive: true });
    writeFileSync(join(root, 'scripts/android/MpzAndroidPlugin.java'), 'plugin');
    writeFileSync(join(main, 'AndroidManifest.xml'), '<manifest><application android:label="MPZ" /></manifest>');
    writeFileSync(join(java, 'MainActivity.java'), 'public class MainActivity extends BridgeActivity { /* keep customization */ }');
    prepareAndroid(root); prepareAndroid(root);
    const manifest = readFileSync(join(main, 'AndroidManifest.xml'), 'utf8');
    const activity = readFileSync(join(java, 'MainActivity.java'), 'utf8');
    expect(manifest.match(/android.permission.READ_CONTACTS/g)).toHaveLength(1);
    expect(manifest.match(/android.permission.ACCESS_FINE_LOCATION/g)).toHaveLength(1);
    expect(manifest.match(/android.permission.ACCESS_COARSE_LOCATION/g)).toHaveLength(1);
    expect(manifest).not.toContain('WRITE_CONTACTS');
    expect(manifest).not.toContain('ACCESS_BACKGROUND_LOCATION');
    expect(manifest).not.toContain('WRITE_EXTERNAL_STORAGE');
    expect(manifest).toContain('android:label="MPZ"');
    expect(activity.match(/registerPlugin\(MpzAndroidPlugin.class\)/g)).toHaveLength(1);
    expect(activity).toContain('keep customization');
  });
  it('registers before the existing bridge initialization without replacing the Activity', () => {
    const root = mkdtempSync(join(tmpdir(), 'mpz-android-'));
    roots.push(root);
    const main = join(root, 'android/app/src/main');
    const java = join(main, 'java/app/lovable/dfc9e1d2017c4c4499328af8ac12f08f');
    mkdirSync(java, { recursive: true });
    mkdirSync(join(root, 'scripts/android'), { recursive: true });
    const plugin = readFileSync(join(process.cwd(), 'scripts/android/MpzAndroidPlugin.java'), 'utf8');
    writeFileSync(join(root, 'scripts/android/MpzAndroidPlugin.java'), plugin);
    writeFileSync(join(main, 'AndroidManifest.xml'), '<manifest><application /></manifest>');
    writeFileSync(join(java, 'MainActivity.java'), 'public class MainActivity extends BridgeActivity { public void onCreate(android.os.Bundle savedInstanceState) { super.onCreate(savedInstanceState); keepCustomLogic(); } }');
    prepareAndroid(root); prepareAndroid(root);
    const activity = readFileSync(join(java, 'MainActivity.java'), 'utf8');
    expect(activity.indexOf('registerPlugin(MpzAndroidPlugin.class)')).toBeLessThan(activity.indexOf('super.onCreate(savedInstanceState)'));
    expect(activity).toContain('keepCustomLogic();');
    expect(readFileSync(join(java, 'MpzAndroidPlugin.java'), 'utf8')).toBe(plugin);
    expect(plugin).not.toContain('WRITE_CONTACTS');
  });
});